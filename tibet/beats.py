for L, ss in S.items():
    W = json.load(open(f'words_{L}.json')); caps = []
    for (t0, s), (t1, _) in zip(ss, ss[1:]):
        end = max([w[1] for w in W if t0 - .05 <= w[0] < t1 - .05] or [t1 - .3])
        words = re.sub(r'(\d) (\d{3})', '\\1\u00a0\\2', s).replace(' —', '').split(' ')
        ch = []; cur = []
        for w in words:
            cur.append(w)
            if len(cur) == 3 or (len(cur) == 2 and len(' '.join(cur)) > 17) or w[-1] in ',.?':
                ch.append(' '.join(cur)); cur = []
        if cur: ch.append(' '.join(cur))
        tot = sum(len(c) + 3 for c in ch); t = t0
        for c in ch:
            d = (end - t0) * (len(c) + 3) / tot; caps.append([round(t, 2), round(t + d, 2), c.rstrip(',.')]); t += d
    json.dump(caps, open(f'caps_{L}.json', 'w'), ensure_ascii=False)
